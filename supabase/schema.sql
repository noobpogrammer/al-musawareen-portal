-- 1. Create Members/Profiles Table
CREATE TABLE IF NOT EXISTS public.members (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    its_id TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    full_name_ar TEXT,
    role TEXT NOT NULL DEFAULT 'photographer',
    mobile TEXT NOT NULL,
    email TEXT NOT NULL,
    city_raza TEXT,
    city_domicile TEXT,
    date_arrival DATE,
    mohalla TEXT,
    dp_url TEXT,
    status TEXT NOT NULL DEFAULT 'pending',
    sharaf_status TEXT NOT NULL DEFAULT 'none',
    sharaf_zone TEXT,
    sharaf_seat TEXT,
    cameras TEXT[],
    lenses TEXT[],
    other_equipment TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Create Miqaats Table
CREATE TABLE IF NOT EXISTS public.miqaats (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL
);

-- 3. Create Sharaf Events Def Table
CREATE TABLE IF NOT EXISTS public.sharaf_events (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT false
);

-- 4. Create Zones Table
CREATE TABLE IF NOT EXISTS public.zones (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT
);

-- 5. Create Topics Table
CREATE TABLE IF NOT EXISTS public.topics (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL
);

-- 6. Create Sharaf Allocations Table
CREATE TABLE IF NOT EXISTS public.sharaf_allocations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    its_number TEXT NOT NULL REFERENCES public.members(its_id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    waaz_zone TEXT,
    mohalla TEXT,
    is_custom_zone BOOLEAN DEFAULT false,
    location TEXT,
    from_time TEXT,
    to_time TEXT
);

-- 7. Create Assignments Table
CREATE TABLE IF NOT EXISTS public.assignments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    date DATE NOT NULL,
    miqaat_name TEXT,
    zone TEXT NOT NULL,
    topics JSONB, -- list of topics or touchpoints
    assigned_users TEXT[], -- Array of ITS numbers
    member_statuses JSONB DEFAULT '{}'::jsonb, -- map of ITS number -> status
    notes TEXT,
    status TEXT NOT NULL DEFAULT 'active',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. Create Assignment Notifications Table
CREATE TABLE IF NOT EXISTS public.assignment_notifications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    assignment_id UUID REFERENCES public.assignments(id) ON DELETE CASCADE,
    its_number TEXT NOT NULL,
    member_name TEXT NOT NULL,
    assignment_title TEXT NOT NULL,
    action TEXT NOT NULL,
    timestamp TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    read BOOLEAN NOT NULL DEFAULT false
);

-- 9. Create Shot Reports Table
CREATE TABLE IF NOT EXISTS public.shot_reports (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    its_number TEXT NOT NULL,
    user_name TEXT NOT NULL,
    assignment_id UUID REFERENCES public.assignments(id) ON DELETE SET NULL,
    assignment_title TEXT NOT NULL,
    drive_link TEXT NOT NULL,
    timestamp TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    notes TEXT,
    grade TEXT NOT NULL DEFAULT 'Pending'
);

-- 10. Create Messages Table
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id UUID NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

